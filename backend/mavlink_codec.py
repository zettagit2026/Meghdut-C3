    rth = build_command_long_payload(target_sys, target_comp, MAV_CMD["NAV_RETURN_TO_LAUNCH"])
    rth_frame = build_packet_v2(76, rth, sequence=(seq + 1) & 0xFF)
    return set_home_frame + rth_frame


