# Reference/default engagement window for the sustained RC_CHANNELS_OVERRIDE
# controlled-landing (PL-011). Commander directive (mirrors the jam-path
# decision): this is NO LONGER an artificial HARD cap. The window is
# OPERATOR-CONTROLLED — honored verbatim, allowed to run long, or run
# continuous-until-stop (see run_sustained_takeover's continuous flag). The
# REAL safety is not a wall-clock ceiling but (a) the operator kill-switch —
# EMERGENCY ABORT / tx_halt / range-auth-off terminate the stream within one
# frame period, and (b) the end-of-window / graceful-stop NEUTRAL-RELEASE burst
# that hands control back to the craft. This constant is retained only as a
# non-binding default reference value (e.g. the spec's advertised default
# window) — it is not enforced as a limit anywhere.
MANEUVER_TAKEOVER_MAX_DURATION_S = 30.0

# Link protocols against which RC_CHANNELS_OVERRIDE (msg 70) is a NO-OP
# (encrypted / frequency-hopping / crypto-bound). A takeover targeting any of
# these is reported not-applicable and NOT transmitted. Match is
# case-insensitive / substring, since detection "protocol" strings vary.
ENCRYPTED_LINK_PROTOCOLS = (
    "elrs", "crsf", "expresslrs", "ocusync", "lightbridge", "dji",
    "dsmx", "dsm2", "spektrum", "frsky", "accst", "access", "flysky",
    "afhds", "hott", "ghst", "tbs", "crossfire", "encrypted", "fhss",
)

# Substrings that positively identify a legacy / unencrypted MAVLink-over-RF
# control link — the ONLY surface RC override actually works against.
LEGACY_MAVLINK_PROTOCOL_TOKENS = ("mavlink", "ardupilot", "px4", "sik")


def classify_override_link(protocol) -> str:
    """Classify a target's control-link protocol string for RC-override
    applicability. Returns one of:

      'encrypted'      — a recognized FHSS/encrypted link: override is a NO-OP.
      'legacy_mavlink' — a recognized legacy/unencrypted MAVLink link.
      'unknown'        — missing/empty/unrecognized protocol.

    Encrypted match takes precedence over legacy (a string mentioning both is
    treated as encrypted / not overridable)."""
    if not protocol:
        return "unknown"
    p = str(protocol).lower()
    if any(tok in p for tok in ENCRYPTED_LINK_PROTOCOLS):
        return "encrypted"
    if any(tok in p for tok in LEGACY_MAVLINK_PROTOCOL_TOKENS):
        return "legacy_mavlink"
    return "unknown"


def link_is_overridable(protocol, legacy_attested: bool = False) -> bool:
    """FAIL-CLOSED applicability gate for a control override (F-3).

    True ONLY when the target link plausibly accepts unauthenticated legacy
    MAVLink RC override:
      * encrypted/FHSS link  => False (NO-OP, refuse).
      * recognized legacy MAVLink link => True.
      * UNKNOWN/empty protocol => fail CLOSED (False) UNLESS the operator has
        explicitly attested the target is legacy MAVLink (legacy_attested=True).
        For a control override an unknown link type must never default to
        'allowed'."""
    cls = classify_override_link(protocol)
    if cls == "encrypted":
        return False
    if cls == "legacy_mavlink":
        return True
    # unknown / empty
    return bool(legacy_attested)


def build_command_long_payload(
    target_system: int,
    target_component: int,
    command: int,
    confirmation: int = 0,
    param1: float = 0.0,
    param2: float = 0.0,
    param3: float = 0.0,
    param4: float = 0.0,
    param5: float = 0.0,
    param6: float = 0.0,
    param7: float = 0.0,
) -> bytes:
    """MAVLink COMMAND_LONG payload (msgid=76). Field order per common.xml."""
    return struct.pack(
        "<fffffffHBBB",
        param1, param2, param3, param4, param5, param6, param7,
        command, target_system, target_component, confirmation,
    )


def _truncate_zero_bytes(payload: bytes) -> bytes:
    """MAVLink v2 payload trimming: drop trailing zero bytes (min 1)."""
    while len(payload) > 1 and payload[-1] == 0:
        payload = payload[:-1]
    return payload


def build_packet_v2(
    msgid: int,
    payload: bytes,
    system_id: int = 255,
    component_id: int = 190,
    sequence: int = 0,
    incompat_flags: int = 0,
    compat_flags: int = 0,
) -> bytes:
    """Assemble a MAVLink v2 frame."""
    if msgid not in CRC_EXTRA:
        raise ValueError(f"CRC_EXTRA not registered for msgid={msgid}")
    trimmed = _truncate_zero_bytes(payload)
    header = struct.pack(
        "<BBBBBBB",
        MAVLINK_STX_V2, len(trimmed), incompat_flags, compat_flags,
        sequence, system_id, component_id,
    )
    # msgid is 24-bit little-endian in v2
    msgid_bytes = bytes([msgid & 0xFF, (msgid >> 8) & 0xFF, (msgid >> 16) & 0xFF])
    frame_wo_crc = header[1:] + msgid_bytes + trimmed  # skip STX for CRC per spec
    crc_input = frame_wo_crc + bytes([CRC_EXTRA[msgid]])
    crc = _crc16_mcrf4xx(crc_input)
    return header + msgid_bytes + trimmed + struct.pack("<H", crc)


def build_packet_v1(
    msgid: int,
    payload: bytes,
    system_id: int = 255,
    component_id: int = 190,
    sequence: int = 0,
) -> bytes:
    """Assemble a MAVLink v1 frame (msgid must be <= 255)."""
    if msgid > 255:
        raise ValueError("MAVLink v1 supports msgid <= 255")
    if msgid not in CRC_EXTRA:
        raise ValueError(f"CRC_EXTRA not registered for msgid={msgid}")
    header = struct.pack(
        "<BBBBBBB",
        MAVLINK_STX_V1, len(payload), sequence, system_id, component_id, msgid,
        0,  # placeholder, not used; v1 header is 6 bytes actually
    )
    # v1 header is 6 bytes: STX,LEN,SEQ,SYSID,COMPID,MSGID
    header = bytes([MAVLINK_STX_V1, len(payload), sequence, system_id, component_id, msgid])
    crc_input = header[1:] + payload + bytes([CRC_EXTRA[msgid]])
    crc = _crc16_mcrf4xx(crc_input)
    return header + payload + struct.pack("<H", crc)


def hexdump(data: bytes, width: int = 16) -> List[str]:
    """Return classical hexdump lines: offset | hex | ascii."""
    lines: List[str] = []
    for offset in range(0, len(data), width):
        chunk = data[offset : offset + width]
        hex_bytes = " ".join(f"{b:02X}" for b in chunk).ljust(width * 3 - 1)
        ascii_bytes = "".join(chr(b) if 32 <= b < 127 else "." for b in chunk)
        lines.append(f"{offset:04X}  {hex_bytes}  |{ascii_bytes}|")
    return lines


def describe_packet(frame: bytes) -> Dict:
    """Human-readable summary of a MAVLink frame."""
    if not frame:
        return {"valid": False, "reason": "empty"}
    stx = frame[0]
    if stx == MAVLINK_STX_V2 and len(frame) >= 12:
        length = frame[1]
        return {
            "valid": True,
            "version": "v2",
            "stx": f"0x{stx:02X}",
            "payload_length": length,
            "incompat_flags": frame[2],
            "compat_flags": frame[3],
            "sequence": frame[4],
            "system_id": frame[5],
            "component_id": frame[6],
            "message_id": frame[7] | (frame[8] << 8) | (frame[9] << 16),
            "total_bytes": len(frame),
        }
    if stx == MAVLINK_STX_V1 and len(frame) >= 8:
        return {
            "valid": True,
            "version": "v1",
            "stx": f"0x{stx:02X}",
            "payload_length": frame[1],
            "sequence": frame[2],
            "system_id": frame[3],
            "component_id": frame[4],
            "message_id": frame[5],
            "total_bytes": len(frame),
        }
    return {"valid": False, "reason": "unknown STX or short frame"}


def iter_frames(blob: bytes) -> List[bytes]:
    """Split a byte blob containing one or more back-to-back MAVLink v1/v2 frames
    into the individual frames. Multi-command payloads (PL-008 spoof-home+RTH,
    PL-005 per-motor DO_MOTOR_TEST) put several frames on the wire in sequence;
    this reverses that so each frame can be inspected/decoded independently.

    Frame length is derived from the header LEN field (v2: STX,LEN(1),incompat,
    compat,seq,sysid,compid + 3-byte msgid + LEN payload + 2-byte CRC = 12+LEN;
    v1: 6-byte header + LEN payload + 2-byte CRC = 8+LEN). Stops at the first
    byte that is not a recognized STX."""
    frames: List[bytes] = []
    i = 0
    n = len(blob)
    while i < n:
        stx = blob[i]
        if stx == MAVLINK_STX_V2 and i + 1 < n:
            total = 12 + blob[i + 1]
        elif stx == MAVLINK_STX_V1 and i + 1 < n:
            total = 8 + blob[i + 1]
        else:
            break
        if i + total > n:
            break
        frames.append(blob[i:i + total])
        i += total
    return frames


def decode_command_long(frame: bytes) -> Dict:
    """Round-trip decoder for a COMMAND_LONG (msgid=76) frame: recovers the seven
    float params + command id + target ids. Used to assert byte-accurate content
    (e.g. PL-008's spoofed lat/lon, PL-005's per-motor number). Zero-pads a
    v2-trimmed payload back to the full 33 bytes before unpacking."""
    payload = _payload_from_frame(frame).ljust(33, b"\x00")[:33]
    (p1, p2, p3, p4, p5, p6, p7, command, target_system, target_component,
     confirmation) = struct.unpack("<fffffffHBBB", payload)
    return {
        "command": command,
        "target_system": target_system,
        "target_component": target_component,
        "confirmation": confirmation,
        "param1": p1, "param2": p2, "param3": p3, "param4": p4,
        "param5": p5, "param6": p6, "param7": p7,
    }


